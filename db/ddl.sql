BEGIN
    FOR t IN (SELECT table_name
                FROM user_tables
               WHERE table_name IN ('RF_COMUNICADO', 'RF_NOTIFICACAO', 'RF_HISTORICO_STATUS', 'RF_OBSERVACAO',
                                    'RF_APOIO', 'RF_FOTO_PROBLEMA', 'RF_PROBLEMA', 'RF_CATEGORIA',
                                    'RF_PARTICIPACAO', 'RF_COMUNIDADE', 'RF_USUARIO')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

CREATE TABLE RF_USUARIO (
    ID           NUMBER(19)         GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME         VARCHAR2(120 CHAR) NOT NULL,
    EMAIL        VARCHAR2(150 CHAR) NOT NULL,
    SENHA_HASH   VARCHAR2(100 CHAR) NOT NULL,
    PERFIL       VARCHAR2(10 CHAR)  NOT NULL,
    ENDERECO     VARCHAR2(255 CHAR),
    LATITUDE     NUMBER(10,7),
    LONGITUDE    NUMBER(10,7),
    ORGANIZACAO  VARCHAR2(150 CHAR),
    CRIADO_EM    TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RF_USUARIO PRIMARY KEY (ID),
    CONSTRAINT UK_RF_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_RF_USUARIO_PERFIL CHECK (PERFIL IN ('GESTOR', 'MORADOR')),
    CONSTRAINT CK_RF_USUARIO_GESTOR CHECK (PERFIL <> 'GESTOR' OR ORGANIZACAO IS NOT NULL),
    CONSTRAINT CK_RF_USUARIO_MORADOR CHECK (PERFIL <> 'MORADOR'
        OR (ENDERECO IS NOT NULL AND LATITUDE IS NOT NULL AND LONGITUDE IS NOT NULL))
);

CREATE TABLE RF_COMUNIDADE (
    ID           NUMBER(19)         GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME         VARCHAR2(120 CHAR) NOT NULL,
    DESCRICAO    VARCHAR2(500 CHAR),
    LATITUDE     NUMBER(10,7)       NOT NULL,
    LONGITUDE    NUMBER(10,7)       NOT NULL,
    ID_GESTOR    NUMBER(19)         NOT NULL,
    CRIADA_EM    TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RF_COMUNIDADE PRIMARY KEY (ID),
    CONSTRAINT FK_RF_COMUNIDADE_GESTOR FOREIGN KEY (ID_GESTOR) REFERENCES RF_USUARIO (ID)
);

CREATE INDEX IX_RF_COMUNIDADE_GESTOR ON RF_COMUNIDADE (ID_GESTOR);

CREATE TABLE RF_PARTICIPACAO (
    ID             NUMBER(19)  GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_USUARIO     NUMBER(19)  NOT NULL,
    ID_COMUNIDADE  NUMBER(19)  NOT NULL,
    ENTROU_EM      TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RF_PARTICIPACAO PRIMARY KEY (ID),
    CONSTRAINT UK_RF_PARTICIPACAO UNIQUE (ID_USUARIO, ID_COMUNIDADE),
    CONSTRAINT FK_RF_PARTICIPACAO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES RF_USUARIO (ID),
    CONSTRAINT FK_RF_PARTICIPACAO_COMUNIDADE FOREIGN KEY (ID_COMUNIDADE)
        REFERENCES RF_COMUNIDADE (ID) ON DELETE CASCADE
);

CREATE INDEX IX_RF_PARTICIPACAO_COMUNIDADE ON RF_PARTICIPACAO (ID_COMUNIDADE);

CREATE TABLE RF_CATEGORIA (
    ID    NUMBER(19)        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME  VARCHAR2(60 CHAR) NOT NULL,
    CONSTRAINT PK_RF_CATEGORIA PRIMARY KEY (ID),
    CONSTRAINT UK_RF_CATEGORIA_NOME UNIQUE (NOME)
);

CREATE TABLE RF_PROBLEMA (
    ID                NUMBER(19)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TITULO            VARCHAR2(120 CHAR)  NOT NULL,
    DESCRICAO         VARCHAR2(1000 CHAR) NOT NULL,
    LATITUDE          NUMBER(10,7)        NOT NULL,
    LONGITUDE         NUMBER(10,7)        NOT NULL,
    ID_AUTOR          NUMBER(19)          NOT NULL,
    ID_COMUNIDADE     NUMBER(19)          NOT NULL,
    ID_CATEGORIA      NUMBER(19),
    ADOTADO           NUMBER(1)           DEFAULT 0 NOT NULL,
    ADOTADO_EM        TIMESTAMP,
    STATUS            VARCHAR2(20 CHAR),
    PRIORIDADE        VARCHAR2(20 CHAR),
    GRAVIDADE_IA      VARCHAR2(10 CHAR),
    JUSTIFICATIVA_IA  VARCHAR2(500 CHAR),
    CRIADO_EM         TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RF_PROBLEMA PRIMARY KEY (ID),
    CONSTRAINT FK_RF_PROBLEMA_AUTOR FOREIGN KEY (ID_AUTOR) REFERENCES RF_USUARIO (ID),
    CONSTRAINT FK_RF_PROBLEMA_COMUNIDADE FOREIGN KEY (ID_COMUNIDADE) REFERENCES RF_COMUNIDADE (ID),
    CONSTRAINT FK_RF_PROBLEMA_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES RF_CATEGORIA (ID),
    CONSTRAINT CK_RF_PROBLEMA_ADOTADO CHECK (ADOTADO IN (0, 1)),
    CONSTRAINT CK_RF_PROBLEMA_STATUS CHECK (STATUS IN ('PENDENTE', 'EM_ANDAMENTO', 'RESOLVIDO', 'ARQUIVADO')),
    CONSTRAINT CK_RF_PROBLEMA_GRAVIDADE CHECK (GRAVIDADE_IA IN ('BAIXA', 'MEDIA', 'ALTA', 'CRITICA')),
    CONSTRAINT CK_RF_PROBLEMA_ADOCAO CHECK (
        (ADOTADO = 0 AND STATUS IS NULL AND ADOTADO_EM IS NULL)
        OR (ADOTADO = 1 AND STATUS IS NOT NULL AND ADOTADO_EM IS NOT NULL))
);

CREATE INDEX IX_RF_PROBLEMA_FEED ON RF_PROBLEMA (ID_COMUNIDADE, CRIADO_EM);
CREATE INDEX IX_RF_PROBLEMA_AUTOR ON RF_PROBLEMA (ID_AUTOR);

CREATE TABLE RF_FOTO_PROBLEMA (
    ID             NUMBER(19)        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_PROBLEMA    NUMBER(19)        NOT NULL,
    DADOS          BLOB              NOT NULL,
    CONTENT_TYPE   VARCHAR2(50 CHAR) NOT NULL,
    TAMANHO_BYTES  NUMBER(10)        NOT NULL,
    CONSTRAINT PK_RF_FOTO_PROBLEMA PRIMARY KEY (ID),
    CONSTRAINT FK_RF_FOTO_PROBLEMA FOREIGN KEY (ID_PROBLEMA)
        REFERENCES RF_PROBLEMA (ID) ON DELETE CASCADE,
    CONSTRAINT CK_RF_FOTO_TAMANHO CHECK (TAMANHO_BYTES > 0 AND TAMANHO_BYTES <= 5242880)
);

CREATE INDEX IX_RF_FOTO_PROBLEMA ON RF_FOTO_PROBLEMA (ID_PROBLEMA);

CREATE TABLE RF_APOIO (
    ID           NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_USUARIO   NUMBER(19) NOT NULL,
    ID_PROBLEMA  NUMBER(19) NOT NULL,
    CRIADO_EM    TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RF_APOIO PRIMARY KEY (ID),
    CONSTRAINT UK_RF_APOIO UNIQUE (ID_USUARIO, ID_PROBLEMA),
    CONSTRAINT FK_RF_APOIO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES RF_USUARIO (ID),
    CONSTRAINT FK_RF_APOIO_PROBLEMA FOREIGN KEY (ID_PROBLEMA)
        REFERENCES RF_PROBLEMA (ID) ON DELETE CASCADE
);

CREATE INDEX IX_RF_APOIO_PROBLEMA ON RF_APOIO (ID_PROBLEMA);

CREATE TABLE RF_OBSERVACAO (
    ID           NUMBER(19)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_PROBLEMA  NUMBER(19)          NOT NULL,
    ID_AUTOR     NUMBER(19)          NOT NULL,
    TEXTO        VARCHAR2(1000 CHAR) NOT NULL,
    CRIADA_EM    TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RF_OBSERVACAO PRIMARY KEY (ID),
    CONSTRAINT FK_RF_OBSERVACAO_PROBLEMA FOREIGN KEY (ID_PROBLEMA)
        REFERENCES RF_PROBLEMA (ID) ON DELETE CASCADE,
    CONSTRAINT FK_RF_OBSERVACAO_AUTOR FOREIGN KEY (ID_AUTOR) REFERENCES RF_USUARIO (ID)
);

CREATE INDEX IX_RF_OBSERVACAO_PROBLEMA ON RF_OBSERVACAO (ID_PROBLEMA);

CREATE TABLE RF_HISTORICO_STATUS (
    ID               NUMBER(19)        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_PROBLEMA      NUMBER(19)        NOT NULL,
    STATUS_ANTERIOR  VARCHAR2(20 CHAR),
    STATUS_NOVO      VARCHAR2(20 CHAR) NOT NULL,
    DATA_HORA        TIMESTAMP         DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RF_HISTORICO_STATUS PRIMARY KEY (ID),
    CONSTRAINT FK_RF_HISTORICO_PROBLEMA FOREIGN KEY (ID_PROBLEMA)
        REFERENCES RF_PROBLEMA (ID) ON DELETE CASCADE,
    CONSTRAINT CK_RF_HISTORICO_ANTERIOR CHECK (STATUS_ANTERIOR IN ('PENDENTE', 'EM_ANDAMENTO', 'RESOLVIDO', 'ARQUIVADO')),
    CONSTRAINT CK_RF_HISTORICO_NOVO CHECK (STATUS_NOVO IN ('PENDENTE', 'EM_ANDAMENTO', 'RESOLVIDO', 'ARQUIVADO'))
);

CREATE INDEX IX_RF_HISTORICO_PROBLEMA ON RF_HISTORICO_STATUS (ID_PROBLEMA);

CREATE TABLE RF_NOTIFICACAO (
    ID           NUMBER(19)         GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_USUARIO   NUMBER(19)         NOT NULL,
    ID_PROBLEMA  NUMBER(19),
    MENSAGEM     VARCHAR2(300 CHAR) NOT NULL,
    PRIORIDADE   VARCHAR2(5 CHAR)   NOT NULL,
    LIDA         NUMBER(1)          DEFAULT 0 NOT NULL,
    CRIADA_EM    TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RF_NOTIFICACAO PRIMARY KEY (ID),
    CONSTRAINT FK_RF_NOTIFICACAO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES RF_USUARIO (ID),
    CONSTRAINT FK_RF_NOTIFICACAO_PROBLEMA FOREIGN KEY (ID_PROBLEMA)
        REFERENCES RF_PROBLEMA (ID) ON DELETE CASCADE,
    CONSTRAINT CK_RF_NOTIFICACAO_PRIORIDADE CHECK (PRIORIDADE IN ('ALTA', 'BAIXA')),
    CONSTRAINT CK_RF_NOTIFICACAO_LIDA CHECK (LIDA IN (0, 1))
);

CREATE INDEX IX_RF_NOTIFICACAO_USUARIO ON RF_NOTIFICACAO (ID_USUARIO, LIDA);

CREATE TABLE RF_COMUNICADO (
    ID             NUMBER(19)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
