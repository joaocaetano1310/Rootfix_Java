CREATE TABLE RF_COMUNICADO (
    ID             NUMBER(19)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_COMUNIDADE  NUMBER(19)          NOT NULL,
    ID_AUTOR       NUMBER(19)          NOT NULL,
    TITULO         VARCHAR2(120 CHAR)  NOT NULL,
    TEXTO          VARCHAR2(2000 CHAR) NOT NULL,
    DESTACADO      NUMBER(1)           DEFAULT 0 NOT NULL,
    CRIADO_EM      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RF_COMUNICADO PRIMARY KEY (ID),
    CONSTRAINT FK_RF_COMUNICADO_COMUNIDADE FOREIGN KEY (ID_COMUNIDADE)
        REFERENCES RF_COMUNIDADE (ID) ON DELETE CASCADE,
    CONSTRAINT FK_RF_COMUNICADO_AUTOR FOREIGN KEY (ID_AUTOR) REFERENCES RF_USUARIO (ID),
    CONSTRAINT CK_RF_COMUNICADO_DESTACADO CHECK (DESTACADO IN (0, 1))
);

CREATE INDEX IX_RF_COMUNICADO_COMUNIDADE ON RF_COMUNICADO (ID_COMUNIDADE, DESTACADO, CRIADO_EM);

